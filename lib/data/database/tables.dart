/// Drift schema v1 (SPEC.md section 7, REQ-008, DD-003).
///
/// Every synchronisable table gets [SyncColumns]: a UUID primary key (no
/// auto-increment), the HLC of its last change and a tombstone instead of
/// physical deletes. Tokens are the exception: they are derived from
/// `items.raw_text` (DD-004) and rebuilt per item, so they carry no sync
/// columns and are not change-logged.
library;

import 'package:drift/drift.dart';

import '../../domain/items/item_enums.dart';
import '../../domain/people/contact_detail.dart';
import '../../domain/sync/change_operation.dart';

/// Columns shared by every synchronisable entity.
mixin SyncColumns on Table {
  /// UUIDv7, generated by the domain layer.
  TextColumn get id => text()();

  /// Packed HLC of the last change (see `Hlc.pack`).
  TextColumn get hlc => text()();

  /// Tombstone: set instead of deleting the row.
  DateTimeColumn get deletedAt => dateTime().nullable()();

  @override
  Set<Column<Object>> get primaryKey => {id};
}

@TableIndex(name: 'items_status', columns: {#status})
@TableIndex(name: 'items_due_at', columns: {#dueAt})
@TableIndex(name: 'items_revisit_at', columns: {#revisitAt})
@TableIndex(name: 'items_requester_id', columns: {#requesterId})
@TableIndex(name: 'items_waiting_on_id', columns: {#waitingOnId})
@TableIndex(name: 'items_context_id', columns: {#contextId})
class Items extends Table with SyncColumns {
  /// Text exactly as captured; the source of truth for tokens (DD-004).
  TextColumn get rawText => text()();
  TextColumn get title => text().nullable()();

  /// Markdown.
  TextColumn get body => text().nullable()();
  TextColumn get type => textEnum<ItemType>().nullable()();
  TextColumn get status => textEnum<ItemStatus>()();
  TextColumn get source => textEnum<ItemSource>()();
  DateTimeColumn get dueAt => dateTime().nullable()();
  DateTimeColumn get revisitAt => dateTime().nullable()();
  TextColumn get requesterId => text().nullable().references(People, #id)();
  TextColumn get waitingOnId => text().nullable().references(People, #id)();
  TextColumn get contextId => text().nullable().references(Contexts, #id)();

  /// When the user last chose *Keep* or *Still waiting* in the weekly review
  /// (AC REQ-051, DD-018 point 8): a user fact, synchronised. The last touch
  /// itself is worked out from this and the HLC, never stored (rule 6).
  DateTimeColumn get reviewedAt => dateTime().nullable()();

  /// High, normal or low, from `*hoog`, `*2`, `*laag` in [rawText] (REQ-050,
  /// DD-004 point 11); follows the text like [dueAt]. Null when the text has
  /// no priority.
  TextColumn get priority => textEnum<ItemPriority>().nullable()();

  /// The day it was asked (REQ-046, DD-018 point 10), date-only as `due_at`;
  /// null: the day it was captured. Stored only when the user changes it.
  DateTimeColumn get askedAt => dateTime().nullable()();

  /// What I promised, in short (REQ-046); null: the item's title.
  TextColumn get promise => text().nullable()();

  /// For a waiting item: the day I expect it by (REQ-047), date-only as
  /// `due_at`; never the deadline.
  DateTimeColumn get expectedAt => dateTime().nullable()();
}

class People extends Table with SyncColumns {
  TextColumn get name => text()();

  /// Birthday as day and month, year optional (DD-012).
  IntColumn get birthdayDay => integer().nullable()();
  IntColumn get birthdayMonth => integer().nullable()();
  IntColumn get birthdayYear => integer().nullable()();

  /// Free Markdown note (REQ-031).
  TextColumn get note => text().nullable()();

  /// The person this one was merged into (DD-015, T3.2b); set together
  /// with the tombstone. A reference to a merged person, for example one
  /// that arrives later through sync, is read as one to this person.
  TextColumn get mergedIntoId => text().nullable().references(People, #id)();

  /// Where the person works and as what (REQ-038, DD-012); both optional.
  TextColumn get organisation => text().nullable()();
  TextColumn get jobTitle => text().nullable()();

  @override
  List<String> get customConstraints => [
    'CHECK ((birthday_day IS NULL) = (birthday_month IS NULL))',
    'CHECK (birthday_year IS NULL OR birthday_day IS NOT NULL)',
    'CHECK (birthday_day IS NULL OR birthday_day BETWEEN 1 AND 31)',
    'CHECK (birthday_month IS NULL OR birthday_month BETWEEN 1 AND 12)',
  ];
}

/// Alternative names that resolve `@name` to a person (REQ-019).
@TableIndex(name: 'person_aliases_person_id', columns: {#personId})
@TableIndex.sql(
  'CREATE INDEX person_aliases_alias ON person_aliases (alias COLLATE NOCASE)',
)
class PersonAliases extends Table with SyncColumns {
  TextColumn get personId => text().references(People, #id)();
  TextColumn get alias => text()();
}

/// Projects; at most two levels deep, enforced in the domain layer.
@TableIndex(name: 'contexts_parent_id', columns: {#parentId})
class Contexts extends Table with SyncColumns {
  TextColumn get name => text()();
  TextColumn get parentId => text().nullable().references(Contexts, #id)();

  /// When the project was archived; null while it is in use (DD-018 point
  /// 6). User data, synchronised like every other column.
  DateTimeColumn get archivedAt => dateTime().nullable()();
}

/// Phone numbers and email addresses of a person (REQ-038, DD-012): a list
/// per person, several of each kind. The value is the text as typed; a
/// normalised form (E.164) is derived, never stored (T3.6, rule 6).
@TableIndex(name: 'contact_details_person_id', columns: {#personId})
@DataClassName('ContactDetailRow')
class ContactDetails extends Table with SyncColumns {
  TextColumn get personId => text().references(People, #id)();
  TextColumn get kind => textEnum<ContactKind>()();
  TextColumn get value => text()();

  /// A standard label (`work`, `mobile`, `private`, `other`, shown
  /// translated) or the user's own text; optional.
  TextColumn get label => text().nullable()();

  /// The order within the person's list.
  IntColumn get sortOrder => integer()();
}

/// "Where was I" (T10.3, REQ-049, DD-018 point 13): on a switch of context,
/// the next step and what I had in mind, on an item or a project (a
/// context), never both and never neither. Open while [resumedAt] is null;
/// resumed notes stay, as history. When it was saved is the time of its
/// HLC, never a column of its own (hard rule 6).
@TableIndex(name: 'snapshots_item_id', columns: {#itemId})
@TableIndex(name: 'snapshots_context_id', columns: {#contextId})
@DataClassName('SnapshotRow')
class Snapshots extends Table with SyncColumns {
  TextColumn get itemId => text().nullable().references(Items, #id)();
  TextColumn get contextId => text().nullable().references(Contexts, #id)();
  TextColumn get nextStep => text().nullable()();
  TextColumn get inMind => text().nullable()();
  DateTimeColumn get resumedAt => dateTime().nullable()();

  @override
  List<String> get customConstraints => [
    'CHECK ((item_id IS NULL) <> (context_id IS NULL))',
    'CHECK (next_step IS NOT NULL OR in_mind IS NOT NULL)',
  ];
}

/// Tags are linked to items through [Tokens] (`#tag` in the raw text).
@TableIndex.sql(
  'CREATE UNIQUE INDEX tags_name_live ON tags (name COLLATE NOCASE) '
  'WHERE deleted_at IS NULL',
)
class Tags extends Table with SyncColumns {
  TextColumn get name => text()();
}

/// Encrypted attachment files (DD-006). The thumbnail path is derived from
/// the attachment id by convention and deliberately has no column (DD-006/D3).
///
/// The owner is an item or a person (business card, REQ-041), never both and
/// never neither.
@TableIndex(name: 'attachments_item_id', columns: {#itemId})
@TableIndex(name: 'attachments_person_id', columns: {#personId})
class Attachments extends Table with SyncColumns {
  TextColumn get itemId => text().nullable().references(Items, #id)();
  TextColumn get personId => text().nullable().references(People, #id)();
  TextColumn get mimeType => text()();
  IntColumn get sizeBytes => integer()();

  /// Location of the encrypted file (for photos: the display version).
  TextColumn get storagePath => text()();

  /// Version of the photo pipeline that produced the file (DD-006/D6).
  IntColumn get pipelineVersion => integer()();

  @override
  List<String> get customConstraints => [
    'CHECK ((item_id IS NULL) <> (person_id IS NULL))',
  ];
}

/// A link from one item to another (REQ-054, DD-004 point 13). Kind `link`
/// is a `[[label]]` in the text of [fromItemId]: [label] is the text between
/// the brackets when it was chosen, user data that ties that text to this
/// target, so renaming the target breaks nothing. Other kinds (the conflict
/// copy of DD-013) have no label.
@TableIndex(name: 'item_links_from', columns: {#fromItemId})
@TableIndex(name: 'item_links_to', columns: {#toItemId})
class ItemLinks extends Table with SyncColumns {
  TextColumn get fromItemId => text().references(Items, #id)();
  TextColumn get toItemId => text().references(Items, #id)();
  TextColumn get kind => text()();

  /// Schema v11 (T10.9).
  TextColumn get label => text().nullable()();
}

/// One completed time of a recurring task (REQ-061, DD-018 point 18): the
/// history *Gedaan* and, with the text, the item's next date. A user fact,
/// synchronised. Its id is a UUIDv5 of the item and [occurrenceOn]
/// (`completionId`), not a UUIDv7: two devices that complete the same time
/// make the same row (DD-003). Schema v12 (T4.7).
@TableIndex(name: 'item_completions_item_id', columns: {#itemId})
class ItemCompletions extends Table with SyncColumns {
  TextColumn get itemId => text().references(Items, #id)();

  /// The date of the completed time, date-only as `items.due_at`.
  DateTimeColumn get occurrenceOn => dateTime()();

  /// The local day it was done, date-only as `items.due_at`: a user fact,
  /// so every device works out the same next date.
  DateTimeColumn get completedOn => dateTime()();
}

/// A pair of items the user said are not duplicates (the duplicate hint →
/// ignore, AC REQ-053). The hint itself is computed, never stored (hard
/// rule 6); this choice is user data and is synchronised. One row per pair,
/// stored with the smaller id first, covers both directions.
@TableIndex(name: 'duplicate_dismissals_item_id', columns: {#itemId})
@TableIndex(name: 'duplicate_dismissals_other_id', columns: {#otherItemId})
class DuplicateDismissals extends Table with SyncColumns {
  TextColumn get itemId => text().references(Items, #id)();
  TextColumn get otherItemId => text().references(Items, #id)();

  @override
  List<String> get customConstraints => ['CHECK (item_id < other_item_id)'];
}

/// Tokens recognised in `items.raw_text` (DD-004). Derived data: rebuilt from
/// the raw text, never synchronised or change-logged.
@TableIndex(name: 'tokens_item_id', columns: {#itemId})
@TableIndex(name: 'tokens_type_value', columns: {#tokenType, #resolvedValue})
class Tokens extends Table {
  /// UUIDv7.
  TextColumn get id => text()();
  TextColumn get itemId => text().references(Items, #id)();
  TextColumn get tokenType => text()();
  TextColumn get rawValue => text()();
  TextColumn get resolvedValue => text().nullable()();
  IntColumn get parserVersion => integer()();

  @override
  Set<Column<Object>> get primaryKey => {id};
}

/// Append-only log of changes to synchronisable entities (REQ-037, DD-003).
///
/// Self-contained: replaying the log on an empty database rebuilds every
/// synchronisable table (see `ChangeLogReplayer`). Written only through
/// `ChangeLogWriter`, together with the change itself.
@TableIndex(name: 'change_log_hlc', columns: {#hlc})
@TableIndex(name: 'change_log_entity', columns: {#entity, #entityId})
class ChangeLog extends Table {
  /// UUIDv7.
  TextColumn get id => text()();

  /// Table name of the changed entity.
  TextColumn get entity => text()();
  TextColumn get entityId => text()();
  TextColumn get hlc => text()();
  TextColumn get operation => textEnum<ChangeOperation>()();

  /// JSON object with the full new values of the changed columns, keyed by
  /// column name; never a reference to the current database state.
  TextColumn get payload => text()();

  /// Version of the payload format (`changeLogFormatVersion`).
  IntColumn get formatVersion => integer()();

  @override
  Set<Column<Object>> get primaryKey => {id};
}

/// Device-local key/value state (e.g. the HLC node id); never synchronised.
class LocalState extends Table {
  TextColumn get key => text()();
  TextColumn get value => text()();

  @override
  Set<Column<Object>> get primaryKey => {key};
}
